from calc import Calculator

def test():
    test_cases = [
        ("(아무것도 안 누름)", [], "0"),
        ("1 2 + 3 =", ["1", "2", "+", "3", "="], "15"),
        ("2 + 3 * 4 =", ["2", "+", "3", "*", "4", "="], "20"),
        ("5 + - 3 =", ["5", "+", "-", "3", "="], "2"),
        ("0 . 1 + 0 . 2 =", ["0", ".", "1", "+", "0", ".", "2", "="], "0.3"),
        ("6 / 3 =", ["6", "/", "3", "="], "2"),
        ("7 / 2 =", ["7", "/", "2", "="], "3.5"),
        ("5 / 0 =", ["5", "/", "0", "="], "0으로 나눌 수 없습니다"),
        ("5 / 0 = 7", ["5", "/", "0", "=", "7"], "0으로 나눌 수 없습니다"),
        ("5 / 0 = C", ["5", "/", "0", "=", "C"], "0"),
        ("1 . . 5", ["1", ".", ".", "5"], "1.5"),
        (".", ["."], "0."),
        ("0 0 7", ["0", "0", "7"], "7"),
        ("1 2 3 BS", ["1", "2", "3", "BS"], "12"),
        ("5 BS", ["5", "BS"], "0"),
        ("9 +/-", ["9", "+/-"], "-9"),
        ("5 0 %", ["5", "0", "%"], "0.5"),
        ("2 + 3 = 4", ["2", "+", "3", "=", "4"], "4"),
        ("2 + 3 = + 4 =", ["2", "+", "3", "=", "+", "4", "="], "9"),
        ("2 + 3 = =", ["2", "+", "3", "=", "="], "5"),
    ]

    passed = 0
    for description, keys, expected in test_cases:
        calc = Calculator()
        actual = ""
        if description != "(아무것도 안 누름)":
            for k in keys:
                actual = calc.press(k)
        else:
            actual = calc.display

        if actual == expected:
            passed += 1
        else:
            print(f"실패: {description}")
            print(f"  입력: {' '.join(keys)}")
            print(f"  기대값: {expected}")
            print(f"  실제값: {actual}")
            return

    print(f"모든 테스트 통과 ({passed}개)")

if __name__ == "__main__":
    test()
